"""Find which signal actually separates the classes on RAGTruth.

The fused pipeline confidence is at chance on RAGTruth (ROC-AUC 0.478). This
script asks which *component* carries the signal, so the detection score for
this dataset can be chosen from measurement rather than from assumption.

Every candidate score is evaluated the same way: ROC-AUC with a percentile
bootstrap CI that resamples **unique queries** (the same way the headline
numbers are computed), plus a paired permutation test on the paired design.

Candidates:
  * ``confidence``       -- the pipeline's fused score (the current one)
  * ``detector``         -- the step-3 XGBoost hallucination probability
  * ``contradiction_rate`` -- share of claims the NLI marked contradicted
  * ``unknown_rate``     -- share of claims the NLI could not decide
  * ``support_rate``     -- share of claims the NLI marked supported
  * ``n_claims``         -- claim count
  * ``answer_length``    -- word count (the control: must be at chance)

Usage:
  python -m scripts.diagnose_ragtruth_signal --limit 100
  python -m scripts.diagnose_ragtruth_signal --limit 100 \
      --out data/ragtruth_signal.json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from src.config import load_config
from src.pipeline import Pipeline
from src.utils.data_loader import load_jsonl


def roc_auc(scores: np.ndarray, labels: np.ndarray) -> float:
    """ROC-AUC via the rank identity; ties get average ranks."""
    pos = labels == 1
    n_pos = int(pos.sum())
    n_neg = int((~pos).sum())
    if n_pos == 0 or n_neg == 0:
        return 0.5
    order = np.argsort(scores, kind="mergesort")
    ranks = np.empty(len(scores), dtype=float)
    ranks[order] = np.arange(1, len(scores) + 1, dtype=float)
    s = scores[order]
    i = 0
    while i < len(s):
        j = i
        while j + 1 < len(s) and s[j + 1] == s[i]:
            j += 1
        if j > i:
            ranks[order[i:j + 1]] = (i + j + 2) / 2.0
        i = j + 1
    sum_pos = float(ranks[pos].sum())
    return (sum_pos - n_pos * (n_pos + 1) / 2.0) / (n_pos * n_neg)


def bootstrap_auc_ci(scores: np.ndarray, labels: np.ndarray,
                     groups: np.ndarray, n_boot: int = 2000,
                     seed: int = 13) -> tuple[float, float]:
    """Percentile bootstrap CI, resampling unique queries.

    Rows that share a query are correlated, so the bootstrap resamples
    *queries* and takes all of their rows together.
    """
    rng = np.random.default_rng(seed)
    uniq = np.unique(groups)
    by_group = {g: np.where(groups == g)[0] for g in uniq}
    out = []
    for _ in range(n_boot):
        picked = rng.choice(uniq, size=len(uniq), replace=True)
        idx = np.concatenate([by_group[g] for g in picked])
        if len(np.unique(labels[idx])) < 2:
            continue
        out.append(roc_auc(scores[idx], labels[idx]))
    if not out:
        return (float("nan"), float("nan"))
    return (float(np.percentile(out, 2.5)), float(np.percentile(out, 97.5)))


def paired_permutation_p(scores: np.ndarray, labels: np.ndarray,
                         groups: np.ndarray, n_perm: int = 5000,
                         seed: int = 13) -> float:
    """Exact-ish paired permutation test.

    The design is paired: two rows share a query and differ in label. Under
    the null, the label of a pair is exchangeable, so the exact null is
    generated by sign-flipping each pair's delta.
    """
    by_group: dict = {}
    for g in np.unique(groups):
        idx = np.where(groups == g)[0]
        by_group[g] = idx

    deltas = []
    for g, idx in by_group.items():
        pos = idx[labels[idx] == 1]
        neg = idx[labels[idx] == 0]
        if len(pos) == 0 or len(neg) == 0:
            continue
        deltas.append(scores[pos].mean() - scores[neg].mean())
    deltas = np.array(deltas)
    if len(deltas) == 0:
        return float("nan")
    observed = abs(deltas.mean())
    rng = np.random.default_rng(seed)
    flips = rng.choice([-1.0, 1.0], size=(n_perm, len(deltas)))
    null = np.abs((flips * deltas).mean(axis=1))
    return float((null >= observed - 1e-12).mean())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", default="data/ragtruth_eval_1000_matched.jsonl")
    ap.add_argument("--index", default="data/index_ragtruth")
    ap.add_argument("--limit", type=int, default=100)
    ap.add_argument("--out", default="data/ragtruth_signal.json")
    args = ap.parse_args()

    cfg = load_config()
    pipe = Pipeline(cfg)
    pipe.load_index(args.index)

    rows = load_jsonl(args.data)
    if args.limit:
        rows = rows[: args.limit]

    records: list[dict] = []
    for i, r in enumerate(rows):
        res = pipe.run(r["query"], answer=r["answer"], label=int(r["label"]),
                       gold_answer=r.get("right_answer"))
        d = res.to_dict()
        claims = d["claims"]
        n = max(1, len(claims))
        verdicts = [c["verdict"] for c in claims]
        records.append({
            "query": r["query"],
            "instance": r.get("row_id") or r["query"],
            "label": int(r["label"]),
            "confidence": float(d["confidence"]),
            "detector_score": float(d.get("detector_score") or 0.0),
            "contradiction_rate": verdicts.count("contradicted") / n,
            "unknown_rate": verdicts.count("unknown") / n,
            "support_rate": verdicts.count("supported") / n,
            "n_claims": float(len(claims)),
            "answer_length": float(len((r["answer"] or "").split())),
        })
        if (i + 1) % 20 == 0:
            print(f"  [{i+1}/{len(rows)}]", flush=True)

    labels = np.array([r["label"] for r in records], dtype=int)
    groups = np.array([r["instance"] for r in records])

    candidates = ["confidence", "detector_score", "contradiction_rate",
                  "unknown_rate", "support_rate", "n_claims", "answer_length"]

    report: dict = {
        "n_rows": len(records),
        "n_unique_instances": int(len(np.unique(groups))),
        "candidates": {},
    }
    for name in candidates:
        scores = np.array([r[name] for r in records], dtype=float)
        auc = roc_auc(scores, labels)
        lo, hi = bootstrap_auc_ci(scores, labels, groups)
        p = paired_permutation_p(scores, labels, groups)
        report["candidates"][name] = {
            "roc_auc": round(auc, 4),
            "roc_auc_ci95": [round(lo, 4), round(hi, 4)],
            "paired_permutation_p": round(p, 4) if p == p else None,
            "mean_label0": round(float(scores[labels == 0].mean()), 4),
            "mean_label1": round(float(scores[labels == 1].mean()), 4),
            "separates": bool(lo > 0.5 or hi < 0.5),
        }
        print(f"{name:22s} AUC={auc:.4f} CI[{lo:.4f},{hi:.4f}] p={p:.4f} "
              f"{'SEPARATES' if (lo > 0.5 or hi < 0.5) else ''}", flush=True)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
