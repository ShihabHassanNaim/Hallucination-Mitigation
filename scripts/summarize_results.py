"""Summarise evaluation results into a Markdown report.

Reads the per-dataset metric files written by ``scripts/evaluate_full.py``
and renders ``data/RESULTS.md`` with the headline numbers and their
bootstrap 95% confidence intervals.

Usage:
  python -m scripts.summarize_results
  python -m scripts.summarize_results --out data/RESULTS.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

DATASETS = [
    ("halueval", "HaluEval QA (length-matched)", "data/metrics_halueval.json"),
    ("truthfulqa", "TruthfulQA", "data/metrics_truthfulqa.json"),
    ("halueval_raw", "HaluEval QA (raw, length-confounded)", "data/metrics_halueval_raw.json"),
]

# The mitigation measurement is a separate run: the rewrite path is
# measured against the no-mitigation baseline on the rows where it fired.
MITIGATION_PATH = "data/mitigation_results.json"

# The length-matched HaluEval split and TruthfulQA are the defensible
# headline results. The raw HaluEval split is reported for transparency
# only: on it, answer word count alone classifies 94.7% of the rows, so it
# measures answer verbosity as much as hallucination.
HEADLINE_ORDER = [
    "halueval",
    "truthfulqa",
    "halueval_raw",
]

HEADLINE = [
    ("detection_accuracy", "Detection Accuracy"),
    ("detection_precision", "Detection Precision"),
    ("detection_recall", "Detection Recall"),
    ("detection_f1", "Detection F1"),
    ("detection_roc_auc", "Detection ROC-AUC"),
    ("detection_aupr", "Detection AUPR"),
    ("precision_at_recall_90", "Precision at Recall 90"),
    ("spearman_rho", "Spearman rho"),
    ("hallucination_reduction_rate", "Hallucination Reduction Rate (HRR)"),
    ("claim_correction_rate", "Claim Correction Rate (CCR)"),
    ("verification_success_rate", "Verification Success Rate (VSR)"),
    ("end_to_end_accuracy", "End-to-End Accuracy"),
]

RETRIEVAL = [
    ("retrieval_recall_at_5", "Retrieval Recall@5"),
    ("retrieval_precision_at_5", "Retrieval Precision@5"),
    ("retrieval_mrr", "Retrieval MRR"),
    ("retrieval_ndcg", "Retrieval nDCG"),
]

CLAIM = [
    ("claim_precision", "Claim Precision"),
    ("claim_recall", "Claim Recall"),
    ("claim_f1", "Claim F1"),
    ("claim_support_rate", "Claim Support Rate"),
]


def _load(path: str) -> dict:
    p = Path(path)
    if not p.exists():
        return {}
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return {}


def _aggregate(data: dict) -> dict:
    """Return the aggregate block, rebuilding it from the rows if absent.

    A metrics file written by a run still in progress carries only
    ``per_query`` — the aggregate block is written at the end — so the
    summary can be produced from a partial run too.
    """
    agg = data.get("aggregate")
    if isinstance(agg, dict) and agg:
        return agg
    rows = data.get("per_query") or data.get("rows") or []
    if not rows:
        return {}
    from scripts.evaluate_full import _aggregate_from_rows

    return _aggregate_from_rows(data.get("dataset") or "unknown", rows)


def _fmt(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, (int, float)):
        return f"{float(value):.4f}"
    return str(value)


def _ci_text(agg: dict, key: str) -> str:
    ci = agg.get(f"{key}_ci95")
    if not ci or len(ci) != 2:
        return ""
    return f" [{ci[0]:.3f}, {ci[1]:.3f}]"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="data/RESULTS.md")
    args = ap.parse_args()

    loaded = {slug: _load(path) for slug, _label, path in DATASETS}
    loaded = {slug: d for slug, d in loaded.items() if d}

    if not loaded:
        raise SystemExit("no metric files found — run scripts/evaluate_full.py first")

    lines: list[str] = []
    lines.append("# Full Evaluation Results — 13-Step Hallucination Pipeline")
    lines.append("")
    lines.append(
        "Generated by `scripts/summarize_results.py`. Intervals are percentile "
        "bootstrap 95% CIs that resample queries, not rows."
    )
    lines.append("")
    lines.append(
        "**How to read these numbers.** Every row is judged on the answer the "
        "dataset supplies, so the detector scores a faithful answer and a "
        "hallucinated answer for the same question separately. The "
        "length-matched HaluEval split and TruthfulQA are the headline "
        "results; the raw HaluEval split is shown for transparency but is "
        "confounded — on it, answer word count alone classifies 94.7% of "
        "rows, so it partly measures answer verbosity rather than "
        "hallucination."
    )
    lines.append("")

    for slug, label, _path in DATASETS:
        data = loaded.get(slug)
        if not data:
            continue
        agg = _aggregate(data)
        lines.append(f"## {label}")
        lines.append("")
        lines.append(f"- Queries evaluated: **{agg.get('n_queries', '—')}**")
        if agg.get("n_unique_queries"):
            lines.append(f"- Unique questions: **{agg['n_unique_queries']}**")
        if data.get("n_failed"):
            lines.append(
                f"- **Rows that failed and were skipped: {data['n_failed']}**"
            )
        lines.append("")

        lines.append("| Metric | Value | 95% CI |")
        lines.append("|---|---|---|")
        for key, name in HEADLINE:
            val = agg.get(key)
            lines.append(f"| {name} | {_fmt(val)} | {_ci_text(agg, key)} |")
        lines.append("")

        # The latency is a measured range, not a point estimate with an
        # interval, so it is reported separately: the mean, the median and
        # the full range of the run that produced the other numbers.
        if agg.get("latency_mean_s") is not None:
            lines.append("| Latency | Value |")
            lines.append("|---|---|")
            lines.append(
                f"| Per-query latency (mean) | {agg['latency_mean_s']:.2f} s |"
            )
            lines.append(
                f"| Per-query latency (median) | {agg['latency_median_s']:.2f} s |"
            )
            lines.append(
                f"| Per-query latency (range) | {agg['latency_min_s']:.2f}"
                f"–{agg['latency_max_s']:.2f} s |"
            )
            lines.append("")

        retrieval_rows = [
            (key, name) for key, name in RETRIEVAL if agg.get(key) is not None
        ]
        if retrieval_rows:
            lines.append("| Retrieval Metric | Value |")
            lines.append("|---|---|")
            for key, name in retrieval_rows:
                lines.append(f"| {name} | {_fmt(agg.get(key))} |")
            lines.append("")

        claim_rows = [
            (key, name) for key, name in CLAIM if agg.get(key) is not None
        ]
        if claim_rows:
            lines.append("| Claim-Level Metric | Value |")
            lines.append("|---|---|")
            for key, name in claim_rows:
                lines.append(f"| {name} | {_fmt(agg.get(key))} |")
            lines.append("")
            lines.append(
                "Claim recall and F1 are measured on the faithful rows only: "
                "on a hallucinated row the benchmark does not say which of the "
                "answer's claims are wrong, so recall is undefined there."
            )
            lines.append("")

        decisions: dict[str, int] = {}
        for row in data.get("per_query") or []:
            d = row.get("decision")
            if d:
                decisions[d] = decisions.get(d, 0) + 1
        if decisions:
            total = sum(decisions.values())
            dist = ", ".join(f"{k} {v} ({v / total:.1%})" for k, v in sorted(decisions.items()))
            lines.append(f"**Decision distribution:** {dist}")
            lines.append("")

    mitigation = _load(MITIGATION_PATH)
    summary = mitigation.get("summary") if isinstance(mitigation, dict) else None
    regen = (summary or {}).get("regenerated_rows") or {}
    if regen.get("delta_bertscore") is not None:
        delta = regen["delta_bertscore"]
        ci = regen.get("delta_bertscore_ci95")
        kept = (summary.get("kept_rows") or {}).get("n")
        rouge = regen.get("delta_rouge_l")

        lines.append("## Mitigation Delta (rewrite vs. no-mitigation baseline)")
        lines.append("")
        lines.append(
            "Measured by `scripts/evaluate_mitigation.py` on the length-matched "
            "HaluEval split. Only the rows where step 10 actually regenerated "
            "are used for the delta; the rows it left alone are unchanged by "
            "construction."
        )
        lines.append("")
        n_unique = regen.get("n_unique_queries") or summary.get("n_unique_queries")
        guarded = summary.get("n_guarded")

        lines.append("| Quantity | Value |")
        lines.append("|---|---|")
        lines.append(f"| Rows evaluated | {summary.get('n_rows')} |")
        if n_unique is not None:
            lines.append(f"| Unique queries | {n_unique} |")
        lines.append(
            f"| Rows regenerated (step 10 fired) | {summary.get('n_regenerated')} |"
        )
        if kept is not None:
            lines.append(f"| Rows left unchanged | {kept} |")
        if guarded is not None:
            lines.append(
                f"| Rows flagged but guarded (answer left intact) | {guarded} |"
            )
        lines.append(
            "| Pre-mitigation BERTScore F1 (regenerated rows) | "
            f"{regen.get('pre_bertscore'):.4f} |"
        )
        lines.append(
            "| Post-mitigation BERTScore F1 (regenerated rows) | "
            f"{regen.get('post_bertscore'):.4f} |"
        )
        ci_text = f" [{ci[0]:+.4f}, {ci[1]:+.4f}]" if ci else ""
        lines.append(
            f"| **Delta BERTScore F1** | **{delta:+.4f}{ci_text}** |"
        )
        if rouge is not None:
            lines.append(f"| Delta ROUGE-L | {rouge:+.4f} |")
        p_bs = regen.get("delta_bertscore_p")
        if p_bs is not None:
            lines.append(
                f"| Delta BERTScore F1 (paired permutation p) | {p_bs:.4f} |"
            )
        lines.append("")

        # The verdict follows the *interval*, not the point estimate. A
        # positive mean whose CI still covers zero is not evidence of an
        # improvement, and saying so would be an overclaim of exactly the
        # kind the CI-separation rule exists to prevent.
        if ci and ci[0] > 0:
            lines.append(
                "The delta is positive and its 95% CI excludes zero, so the "
                "rewrite improved similarity to the gold answer on the rows "
                "where it fired."
            )
        elif ci and ci[1] < 0:
            lines.append(
                "**This delta is not positive.** The 95% CI excludes zero on "
                "the negative side, so the rewrite did not improve similarity "
                "to the gold answer on the rows where it fired. Dale 2023 "
                "reports +0.49 to +0.60 on machine translation, so the "
                "pipeline does not lead on this dimension. The rewrite path "
                "is implemented and exercised; improving it is future work."
            )
        else:
            lines.append(
                "**This delta is not distinguishable from zero.** The 95% CI "
                "covers zero, so the measurement does not show that the "
                "rewrite improved similarity to the gold answer on the rows "
                "where it fired, and it does not show that it hurt either. "
                "Dale 2023 reports +0.49 to +0.60 on machine translation, so "
                "the pipeline does not lead on this dimension. The rewrite "
                "path is implemented and exercised; improving it is future "
                "work."
            )
        lines.append("")
        lines.append(
            "Statistics are computed over unique queries rather than rows: the "
            "evaluation file pairs a faithful answer with a hallucinated one "
            "for the same question, so the two rows of a query share an answer "
            "and are not independent. The CI is a percentile bootstrap over "
            "queries and the p-value is a paired permutation test that "
            "sign-flips each query's delta."
        )
        lines.append("")

    lines.append("## Cross-Dataset Summary")
    lines.append("")
    summary_slugs = [s for s in HEADLINE_ORDER if s in loaded]
    lines.append("| Metric | " + " | ".join(
        label for slug, label, _ in DATASETS if slug in summary_slugs) + " |")
    lines.append("|---" * (1 + len(summary_slugs)) + "|")
    for key, name in HEADLINE:
        cells = []
        for slug, _label, _path in DATASETS:
            if slug not in summary_slugs:
                continue
            agg = _aggregate(loaded[slug])
            cells.append(_fmt(agg.get(key)))
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
