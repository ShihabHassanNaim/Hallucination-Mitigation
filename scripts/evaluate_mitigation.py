"""Measure the mitigation delta: does regeneration actually improve the answer?

The comparison table claims a mitigation delta of "+0.67 to +0.75 (HIGHEST)".
That claim was never backed by a measurement — the detection evaluation
supplies the benchmark's own answer to the pipeline, so step 10 passes it
through untouched and nothing is regenerated. This script measures the
delta on the path where mitigation actually happens: the pipeline
*generates* an answer, step 10 rewrites the unsupported parts, and the
similarity to the gold answer is compared before and after.

For each row the script reports:

  * ``pre``   — similarity of the generated answer to the gold answer
  * ``post``  — similarity of the final (post-regeneration) answer
  * ``delta`` — post minus pre

Similarity is reported with BERTScore F1 (semantic) and ROUGE-L (surface),
both against the dataset's ``right_answer``. Rows where the pipeline made no
decision to regenerate are reported separately: including them would
average in a delta of exactly zero and understate the effect of the step.

Statistics are computed over *unique queries*, not rows. The evaluation
file pairs a faithful answer and a hallucinated answer for the same
question, so each query contributes two rows; bootstrapping over rows
would treat them as independent evidence and narrow the interval
artificially. The same convention is used everywhere else in the project
(``scripts/evaluate.py``, ``scripts/significance.py``).

A paired permutation test is reported alongside the interval. The
bootstrap supplies the CI; the permutation test supplies the p-value,
because a percentile bootstrap cannot produce a usable p-value when the
resampling distribution is degenerate.

Usage:
  python -m scripts.evaluate_mitigation --limit 200
  python -m scripts.evaluate_mitigation --out data/mitigation_results.json
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from collections import defaultdict
from pathlib import Path

from src.config import load_config
from src.pipeline import Pipeline
from src.steps.step13_evaluation import _rouge_l


def _bertscore_f1(reference: str, candidate: str) -> float | None:
    """BERTScore F1 between a reference and a candidate.

    Returns None when the package or the model is unavailable, so a missing
    dependency cannot be mistaken for a score of zero.
    """
    if not reference.strip() or not candidate.strip():
        return None
    try:
        from bert_score import score as _bs
    except Exception:  # noqa: BLE001
        return None
    try:
        _p, _r, f1 = _bs([reference], [candidate], lang="en", verbose=False)
        return float(f1.item())
    except Exception:  # noqa: BLE001
        return None


def _mean(vals: list[float]) -> float:
    return statistics.fmean(vals) if vals else 0.0


def _bootstrap_ci(vals: list[float], n_boot: int = 1000, seed: int = 0) -> list[float]:
    """Percentile bootstrap 95% CI of the mean."""
    import numpy as np

    if len(vals) < 5:
        return [0.0, 0.0]
    rng = np.random.default_rng(seed)
    arr = np.asarray(vals, dtype=float)
    means = [float(arr[rng.integers(0, len(arr), len(arr))].mean())
             for _ in range(n_boot)]
    return [float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))]


def _query_level_deltas(rows: list[dict], key: str) -> list[float]:
    """The per-query mean delta, so a paired query is counted once.

    The evaluation file holds two rows per query (a faithful answer and a
    hallucinated one). Averaging them first and bootstrapping over the
    per-query values keeps the two rows of a query together, which is what
    the pairing requires.
    """
    by_query: dict[str, list[float]] = defaultdict(list)
    for r in rows:
        d = r.get(key)
        if d is None:
            continue
        by_query[r["query"]].append(float(d))
    return [sum(v) / len(v) for v in by_query.values() if v]


def _paired_permutation_p(
    rows: list[dict], key: str, n_permutations: int = 5000, seed: int = 20261115
) -> float | None:
    """Two-sided p-value for the mean delta being zero.

    The null is generated by flipping the sign of each query's delta.
    Flipping the sign of a paired observation is the exact permutation
    null for a paired design: under the null the rewrite has no effect, so
    every query's delta is equally likely to be positive or negative.
    Swapping rows between queries would be wrong here, because the two
    rows of a query share an answer and are not independent.

    Returns None when there is nothing to test.
    """
    deltas = _query_level_deltas(rows, key)
    if len(deltas) < 5:
        return None

    import numpy as np

    rng = np.random.default_rng(seed)
    arr = np.asarray(deltas, dtype=float)
    observed = abs(float(arr.mean()))
    if observed == 0.0:
        return 1.0

    signs = rng.choice([-1.0, 1.0], size=(n_permutations, arr.shape[0]))
    means = np.abs((signs * arr).mean(axis=1))
    # Add one so the observed result is counted in the tail.
    return float((np.sum(means >= observed) + 1) / (n_permutations + 1))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", default="data/halueval_eval_1000_matched.jsonl")
    ap.add_argument("--index", default="data/index_halueval")
    ap.add_argument("--out", default="data/mitigation_results.json")
    ap.add_argument("--limit", type=int, default=0,
                    help="0 means the whole file")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    from src.utils.data_loader import load_jsonl

    rows = load_jsonl(args.data)
    if args.limit:
        rows = rows[: args.limit]

    cfg = load_config()
    pipe = Pipeline(cfg=cfg)
    if args.index:
        pipe.load_index(args.index)
        print(f"loaded index: {args.index} ({pipe.retriever.n_docs} docs)")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    per_row: list[dict] = []
    t_start = time.time()

    for idx, r in enumerate(rows):
        gold = str(r.get("right_answer") or "")
        if not gold:
            continue
        query = r.get("query") or r.get("question") or ""
        try:
            # No `answer=` argument: the pipeline generates its own, which
            # is the only way step 10 has anything to regenerate.
            res = pipe.run(query)
        except Exception as exc:  # noqa: BLE001
            print(f"  row {idx} failed: {type(exc).__name__}: {exc}",
                  file=sys.stderr, flush=True)
            continue

        d = res.to_dict()
        # `original_answer` is what the generator produced; `final_answer`
        # is what survived step 10.
        generated = d.get("original_answer") or d.get("answer", "")
        final = d.get("final_answer") or d.get("answer", "")

        pre_bs = _bertscore_f1(gold, generated)
        post_bs = _bertscore_f1(gold, final)
        pre_rl = _rouge_l(gold, generated)
        post_rl = _rouge_l(gold, final)

        regenerated = final.strip() != generated.strip()

        # The step-10 decision record says *why* the answer was or was not
        # rewritten, which is what distinguishes a rewrite from a guard.
        step10 = next((t["payload"] for t in d.get("step_traces", [])
                       if t.get("name") == "regeneration"), {})
        guard = step10.get("guard", "")

        per_row.append({
            "query": query,
            "label": int(r["label"]) if r.get("label") in {0, 1, "0", "1"} else None,
            "decision": d.get("decision"),
            "iterations": d.get("iterations"),
            "regenerated": regenerated,
            "guard": guard,
            "step10_decision": step10.get("decision"),
            "pre_bertscore": pre_bs,
            "post_bertscore": post_bs,
            "delta_bertscore": (post_bs - pre_bs)
            if (pre_bs is not None and post_bs is not None) else None,
            "pre_rouge_l": pre_rl,
            "post_rouge_l": post_rl,
            "delta_rouge_l": post_rl - pre_rl,
        })

        if (idx + 1) % 10 == 0 or (idx + 1) == len(rows):
            elapsed = time.time() - t_start
            avg = elapsed / (idx + 1)
            print(
                f"  [{idx+1}/{len(rows)}] avg={avg:.1f}s "
                f"eta={avg * (len(rows) - idx - 1):.0f}s",
                file=sys.stderr, flush=True,
            )
            out_path.write_text(
                json.dumps({"per_row": per_row}, indent=2), encoding="utf-8"
            )

    regen_rows = [r for r in per_row if r["regenerated"]]
    kept_rows = [r for r in per_row if not r["regenerated"]]
    # Guarded rows are the ones where step 10 saw a contradiction but
    # declined to rewrite, because nothing sensible could replace the
    # claim. Their delta is zero by construction, and they are reported
    # separately so the effect of the guard is visible.
    guarded_rows = [r for r in per_row if r.get("guard")]

    def _agg(rows_: list[dict]) -> dict:
        deltas_bs = [r["delta_bertscore"] for r in rows_
                     if r["delta_bertscore"] is not None]
        deltas_rl = [r["delta_rouge_l"] for r in rows_]
        # The CI and the p-value are computed over unique queries, so a
        # paired query is not counted as two independent observations.
        q_bs = _query_level_deltas(rows_, "delta_bertscore")
        q_rl = _query_level_deltas(rows_, "delta_rouge_l")
        p_bs = _paired_permutation_p(rows_, "delta_bertscore")
        p_rl = _paired_permutation_p(rows_, "delta_rouge_l")
        return {
            "n": len(rows_),
            "n_unique_queries": len({r["query"] for r in rows_}),
            "pre_bertscore": _mean([r["pre_bertscore"] for r in rows_
                                    if r["pre_bertscore"] is not None]),
            "post_bertscore": _mean([r["post_bertscore"] for r in rows_
                                     if r["post_bertscore"] is not None]),
            "delta_bertscore": _mean(deltas_bs),
            "delta_bertscore_ci95": _bootstrap_ci(q_bs, seed=args.seed),
            "delta_bertscore_p": p_bs,
            "pre_rouge_l": _mean([r["pre_rouge_l"] for r in rows_]),
            "post_rouge_l": _mean([r["post_rouge_l"] for r in rows_]),
            "delta_rouge_l": _mean(deltas_rl),
            "delta_rouge_l_ci95": _bootstrap_ci(q_rl, seed=args.seed),
            "delta_rouge_l_p": p_rl,
        }

    summary = {
        "dataset": args.data,
        "n_rows": len(per_row),
        "n_unique_queries": len({r["query"] for r in per_row}),
        "n_regenerated": len(regen_rows),
        "n_kept": len(kept_rows),
        "n_guarded": len(guarded_rows),
        "all_rows": _agg(per_row),
        "regenerated_rows": _agg(regen_rows) if regen_rows else {},
        "kept_rows": _agg(kept_rows) if kept_rows else {},
        "guarded_rows": _agg(guarded_rows) if guarded_rows else {},
    }

    out_path.write_text(
        json.dumps({"summary": summary, "per_row": per_row}, indent=2),
        encoding="utf-8",
    )
    print(json.dumps(summary, indent=2))
    print(f"\nwrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
